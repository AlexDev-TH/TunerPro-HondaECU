"""Generate src/ecmids.inc from HondaECU's src/ecmids.py.

ecmids.py is a plain dict literal, so it is parsed with ast and never executed.
Usage: python -I gen_ecmids.py <path to ecmids.py> <output .inc>
"""
import ast
import sys

src = open(sys.argv[1], encoding="utf-8").read()
tree = ast.parse(src)
table = None
for node in tree.body:
    if isinstance(node, ast.Assign) and node.targets[0].id == "ECM_IDs":
        table = ast.literal_eval(node.value)
if table is None:
    sys.exit("ECM_IDs not found")


def num(entry, key):
    return int(entry[key], 16) if key in entry else -1


with open(sys.argv[2], "w", encoding="ascii", newline="\n") as out:
    out.write("// Generated by tools/gen_ecmids.py from HondaECU src/ecmids.py. Do not edit.\n")
    for key, e in table.items():
        idbytes = ", ".join("0x%02x" % b for b in key)
        out.write('{{%s}, "%s", "%s", "%s", %d, %d, %d, %d},\n' % (
            idbytes, e["model"], e["year"], e["pn"],
            num(e, "checksum"), num(e, "offset"), num(e, "ecmidaddr"), num(e, "keihinaddr")))
print(len(table), "entries")
