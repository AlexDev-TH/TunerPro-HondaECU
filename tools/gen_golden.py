"""Generate tests/golden.inc from the HondaECU Python sources.

Every send_command() call with literal arguments in eculib/honda.py and threads/kline.py is
pulled out with ast, and the pure helper functions run from the original source, so the C++
port is checked against HondaECU's own bytes rather than a hand-typed copy.

Usage: python -I gen_golden.py <HondaECU root> <output .inc>
"""
import ast
import os
import struct
import sys

root, out_path = sys.argv[1], sys.argv[2]
honda_src = open(os.path.join(root, "eculib", "honda.py"), encoding="utf-8").read()
kline_src = open(os.path.join(root, "src", "threads", "kline.py"), encoding="utf-8").read()

# Only these pure functions get executed; everything else in the file is just parsed.
WANTED = {"format_read", "checksum8bitHonda", "checksum8bit", "validate_checksums", "do_validation", "format_message"}
tree = ast.parse(honda_src)
scope = {"struct": struct}
for node in tree.body:
    if isinstance(node, ast.FunctionDef) and node.name in WANTED:
        exec(compile(ast.Module([node], []), "honda.py", "exec"), scope)
assert WANTED <= set(scope), "missing helper in honda.py"


def literal(node):
    try:
        value = ast.literal_eval(node)
    except ValueError:
        return None
    if isinstance(value, list) and all(isinstance(x, int) for x in value):
        return value
    return None


commands = []
for source in (honda_src, kline_src):
    for node in ast.walk(ast.parse(source)):
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) and node.func.attr == "send_command":
            if not node.args:
                continue
            mtype = literal(node.args[0])
            if mtype is None:
                continue
            data = [] if len(node.args) < 2 else literal(node.args[1])
            if data is None:
                continue
            if (mtype, data) not in commands:
                commands.append((mtype, data))


# ping() builds its data from a default argument rather than a literal list.
for node in ast.walk(tree):
    if isinstance(node, ast.FunctionDef) and node.name == "ping":
        mode = ast.literal_eval(node.args.defaults[0])
        if ([254], [mode]) not in commands:
            commands.append(([254], [mode]))


def c_bytes(values):
    return "{" + ", ".join("0x%02X" % v for v in values) + "}"


with open(out_path, "w", encoding="ascii", newline="\n") as out:
    out.write("// Generated by tools/gen_golden.py from the HondaECU sources. Do not edit.\n")
    out.write("static const GoldenFrame kGoldenFrames[] = {\n")
    for mtype, data in commands:
        frame, _, _ = scope["format_message"](mtype, data)
        out.write("    {%s, %s, %s},\n" % (c_bytes(mtype), c_bytes(data), c_bytes(frame)))
    out.write("};\n\n")

    out.write("static const GoldenRead kGoldenReads[] = {\n")
    for location in (0, 12, 0x8000, 0x12345, 0x3FFF8, 0xFFFF4):
        out.write("    {0x%X, %s},\n" % (location, c_bytes(scope["format_read"](location))))
    out.write("};\n\n")

    out.write("static const GoldenChecksum kGoldenChecksums[] = {\n")
    samples = [
        list(range(1, 9)),
        [0xFF] * 132,
        [0x00, 0x10] + [0xA5] * 128 + [0x00, 0x18],
        [0x01] * 3 + [0xFE] * 40,
    ]
    for sample in samples:
        out.write("    {%s, 0x%02X, 0x%02X},\n" % (c_bytes(sample), scope["checksum8bitHonda"](sample), scope["checksum8bit"](sample)))
    out.write("};\n\n")

    out.write("static const GoldenValidation kGoldenValidations[] = {\n")
    image = [0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88]
    for cksum in (-1, 0, 3, 7, 8):
        ok, status, fixed = scope["do_validation"](bytearray(image), len(image), cksum)
        out.write('    {%s, %d, "%s", %s},\n' % (c_bytes(image), cksum, status, c_bytes(list(fixed))))
    good = list(image)
    good[0] = scope["checksum8bitHonda"](good[1:])
    ok, status, fixed = scope["do_validation"](bytearray(good), len(good), -1)
    out.write('    {%s, -1, "%s", %s},\n' % (c_bytes(good), status, c_bytes(list(fixed))))
    out.write("};\n")

print(len(commands), "literal commands")
